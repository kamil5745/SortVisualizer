/**
 * Общий интерфейс всех сортировок (паттерн "Стратегия").
 * Чтобы добавить новую сортировку, достаточно написать класс с этим интерфейсом
 * и дописать его в список ALGORITHMS в классе Main.
 */
public interface Sorter {

    /** Название алгоритма для меню и для итоговой статистики. */
    String getName();

    /**
     * Сортирует массив по возрастанию.
     *
     * @param array   массив (уже копия исходного, менять можно)
     * @param viz     визуализатор: рисует кадры между шагами
     * @param metrics счётчики сравнений и перестановок/записей
     */
    void sort(int[] array, Visualizer viz, Metrics metrics);
}
